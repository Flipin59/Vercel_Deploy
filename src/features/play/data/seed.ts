// Turns the question bank (questions/*.json) into SQL for play_questions. Re-run after
// editing the JSON and save the output as a new migration:
//   node --experimental-strip-types src/features/play/data/seed.ts \
//     > supabase/migrations/<YYYYMMDDHHMMSS>_play_questions_seed.sql
// Existing rows are updated in place; calibration counters are kept.
import { readdirSync, readFileSync } from "node:fs";

const dir = new URL("./questions/", import.meta.url);
const text = (v: string | undefined) => (v == null ? "null" : `'${v.replaceAll("'", "''")}'`);

const rows = readdirSync(dir)
  .filter((f) => f.endsWith(".json"))
  .sort()
  .flatMap((f) => JSON.parse(readFileSync(new URL(f, dir), "utf8")))
  .map((q) =>
    `  (${[q.id, q.pillar].map(text)}, array[${q.tags.map(text)}], ${[q.tier, q.type].map(text)}, ` +
    `${text(JSON.stringify(q.content))}::jsonb, ${[q.reel_id, q.chapter_slug, q.status, q.source].map(text)})`,
  );

console.log(`-- Generated by src/features/play/data/seed.ts. Edit the JSON, not this file.
insert into play_questions (id, pillar, tags, tier, type, content, reel_id, chapter_slug, status, source) values
${rows.join(",\n")}
on conflict (id) do update set
  pillar = excluded.pillar, tags = excluded.tags, tier = excluded.tier, type = excluded.type,
  content = excluded.content, reel_id = excluded.reel_id, chapter_slug = excluded.chapter_slug,
  status = excluded.status, source = excluded.source;`);
